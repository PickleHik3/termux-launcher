package com.termux.app.terminal;

import android.app.Application;
import androidx.test.core.app.ApplicationProvider;
import android.os.Build;

import com.termux.shared.termux.settings.preferences.TerminalContrastLevel;

import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;
import org.junit.runner.RunWith;
import org.robolectric.RobolectricTestRunner;
import org.robolectric.annotation.Config;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Locale;
import java.util.Properties;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;

/**
 * Shells watch the exported palette by modification time, so rewriting identical content is not
 * free — it makes every open shell re-source on its next prompt.
 */
@RunWith(RobolectricTestRunner.class)
@Config(sdk = Build.VERSION_CODES.P, application = Application.class)
public class MaterialColorExportWriteTest {

    @Rule public TemporaryFolder folder = new TemporaryFolder();

    /** The regression: a line-joining reader drops the trailing newline these files end with. */
    @Test
    public void contentEndingInANewlineStillMatchesItself() throws Exception {
        String content = "# Generated by Termux. Do not edit.\nprimary=#FFB3AE\nsurface=#1A1111\n";
        File file = folder.newFile("material-colors.properties");
        Files.write(file.toPath(), content.getBytes(StandardCharsets.UTF_8));

        assertTrue(MaterialTerminalColorScheme.alreadyOnDisk(file.getAbsolutePath(), content));
    }

    @Test
    public void changedContentDoesNotMatch() throws Exception {
        File file = folder.newFile("material-colors.sh");
        Files.write(file.toPath(), "export A='#000000'\n".getBytes(StandardCharsets.UTF_8));

        assertFalse(MaterialTerminalColorScheme.alreadyOnDisk(file.getAbsolutePath(),
            "export A='#FFFFFF'\n"));
        // Same length, different bytes — a length-only check would call this a match.
        assertFalse(MaterialTerminalColorScheme.alreadyOnDisk(file.getAbsolutePath(),
            "export B='#000000'\n"));
    }

    @Test
    public void aTruncatedOrExtendedFileDoesNotMatch() throws Exception {
        File file = folder.newFile("trunc.properties");
        Files.write(file.toPath(), "a=1\nb=2\n".getBytes(StandardCharsets.UTF_8));

        assertFalse(MaterialTerminalColorScheme.alreadyOnDisk(file.getAbsolutePath(), "a=1\n"));
        assertFalse(MaterialTerminalColorScheme.alreadyOnDisk(file.getAbsolutePath(),
            "a=1\nb=2\nc=3\n"));
    }

    /**
     * Turkish maps {@code i} to a dotted capital I, so a default-locale upper-case turned
     * {@code primary} into {@code PRİMARY} — not a shell identifier, and the file stopped sourcing.
     */
    @Test
    public void shellExportNamesDoNotFollowTheDeviceLocale() {
        Locale original = Locale.getDefault();
        try {
            Locale.setDefault(new Locale("tr", "TR"));
            Properties props = new Properties();
            props.setProperty("primary", "#FFB3AE");
            props.setProperty("terminal_bright_white", "#EEEEEE");

            String exports = MaterialTerminalColorScheme.toShellExports(props);

            assertTrue(exports, exports.contains("export TERMUX_MATERIAL_PRIMARY="));
            assertTrue(exports, exports.contains("export TERMUX_MATERIAL_TERMINAL_BRIGHT_WHITE="));
            assertFalse(exports, exports.contains("PRİMARY"));
        } finally {
            Locale.setDefault(original);
        }
    }

    /**
     * The files are sourced, not read: a truncating write leaves a window in which a starting shell
     * sources half a palette. The rewrite goes through a sibling and a rename, and takes the sibling
     * with it.
     */
    @Test
    public void aRewriteReplacesTheFileInOneStepAndLeavesNothingBehind() throws Exception {
        File file = folder.newFile("material-colors.sh");
        Files.write(file.toPath(), "export A='#000000'\n".getBytes(StandardCharsets.UTF_8));

        MaterialTerminalColorScheme.writeFile(file.getAbsolutePath(), "export A='#FFFFFF'\n");

        assertEquals("export A='#FFFFFF'\n",
            new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8));
        File[] leftovers = folder.getRoot().listFiles((dir, name) -> name.endsWith(".new"));
        assertNotNull(leftovers);
        assertEquals(0, leftovers.length);
    }

    @Test
    public void aMissingFileNeverMatches() {
        assertFalse(MaterialTerminalColorScheme.alreadyOnDisk(
            new File(folder.getRoot(), "absent.properties").getAbsolutePath(), "a=1\n"));
    }

    /**
     * The exported files describe exactly the palette the terminal was given: the solver's pair
     * table moves slots 1, 4, 7 and 15, and a writer that re-derived them would hand shells and
     * kitty a palette the contract test never saw. Checked on the properties text and the noctalia
     * aliases, for the grid's seeds.
     */
    @Test
    public void exportedAnsiValuesEqualTheSolvedPalette() {
        MaterialTerminalColorScheme.Seeds[] seeds = {
            new MaterialTerminalColorScheme.Seeds(0xFF0C141B, 0xFFDCE3ED, 0xFF93CCFF, 0xFFF2B8B5),
            new MaterialTerminalColorScheme.Seeds(0xFFF8F9FF, 0xFF191C20, 0xFF3A608F, 0xFFBA1A1A)};
        String[] ansiNames = {"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"};
        for (MaterialTerminalColorScheme.Seeds seed : seeds) {
            for (TerminalContrastLevel level : TerminalContrastLevel.values()) {
                Properties palette = MaterialTerminalColorScheme.build(seed, level, 0, null);
                Properties roles = MaterialTerminalColorScheme.createMaterialRoleProperties(
                    ApplicationProvider.getApplicationContext(), palette, level);
                String text = MaterialTerminalColorScheme.toPropertiesText(roles);
                for (int slot = 0; slot < 16; slot++) {
                    String solved = palette.getProperty("color" + slot);
                    assertEquals("color" + slot + " at " + level.value, solved,
                        roles.getProperty("terminal_color" + slot));
                    assertTrue("color" + slot + " in the written text",
                        text.contains("terminal_color" + slot + "=" + solved + "\n"));
                    String alias = (slot < 8 ? "terminal_normal_" : "terminal_bright_")
                        + ansiNames[slot % 8];
                    assertEquals(alias + " at " + level.value, solved, roles.getProperty(alias));
                }
            }
        }
    }
}
