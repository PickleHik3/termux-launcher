package com.termux.app.chrome.scene;

/**
 * The AGSL of the three design scenes, each stripped to its own scene function, the helpers that
 * function calls, {@code finishColor} and {@code main}. The math is the design tool's, verbatim;
 * only the five unused scene functions and their helpers are gone. Uniforms: {@code uResolution}
 * (px) and {@code uTime} (seconds), height-normalised coordinates with Y flipped, as designed.
 */
final class DesignSceneSources {

    static final String CONTOUR_WAVES =
          "uniform float2 uResolution;\n"
        + "uniform float uTime;\n"
        + "const float PI = 3.14159265359;\n"
        + "const float TAU = 6.28318530718;\n"
        + "float2 rotatePoint(float2 p,float a) {\n"
        + "    return float2(cos(a)*p.x-sin(a)*p.y,sin(a)*p.x+cos(a)*p.y);\n"
        + "}\n"
        + "float3 contours(float2 p,float t) {\n"
        + "    float2 q=rotatePoint(p,.23);\n"
        + "    float hill=exp(-dot((q-float2(.22,.1))*float2(.85,.72),(q-float2(.22,.1))*float2(.85,.72)));\n"
        + "    float warp=.25*sin(q.y*1.35+t*.055)+.20*sin(q.y*2.3-q.x*.65-t*.037);\n"
        + "    float field=(q.x+warp+.50*hill+.065*sin(q.y*4.0+t*.04))*24.0;\n"
        + "    float phase=fract(field);\n"
        + "    float distanceToLine=min(phase,1.0-phase);\n"
        + "    float aa=clamp(30.0/uResolution.y,.014,.13);\n"
        + "    float line=1.0-smoothstep(.019,.019+aa,distanceToLine);\n"
        + "    float halo=exp(-distanceToLine*distanceToLine*95.0);\n"
        + "    float chosen=pow(.5+.5*sin(floor(field)*2.399),14.0);\n"
        + "    float travel=pow(.5+.5*sin(q.y*2.0+floor(field)*.075-t*.25),18.0);\n"
        + "    float hue=smoothstep(-1.3,1.35,q.x+.23*q.y);\n"
        + "    float3 pigment=mix(float3(.015,.32,1.0),float3(.78,.035,.62),hue);\n"
        + "    pigment=mix(pigment,float3(.015,.87,.95),exp(-pow((q.x+.7)*2.5,2.0))*.8);\n"
        + "    pigment=mix(pigment,float3(1.0,.32,.07),smoothstep(.5,1.5,q.x-q.y*.2));\n"
        + "    float light=.24+.7*chosen+.85*travel;\n"
        + "    return float3(.002,.004,.012)+pigment*(line*light+halo*.035);\n"
        + "}\n"
        + "float3 finishColor(float3 color,float2 p) {\n"
        + "    // A restrained filmic shoulder preserves saturated highlights.\n"
        + "    color=1.0-exp(-max(color,float3(0.0))*1.65);\n"
        + "    color*=1.0-.12*smoothstep(.55,2.2,length(p*float2(.65,1.0)));\n"
        + "    return pow(max(color,float3(0.0)),float3(.91));\n"
        + "}\n"
        + "half4 main(float2 fragCoord) {\n"
        + "    float2 p=(fragCoord-.5*uResolution)/uResolution.y*2.0;\n"
        + "    p.y=-p.y;\n"
        + "    float3 color=finishColor(contours(p,uTime),p);\n"
        + "    return half4(half3(color),1.0);\n"
        + "}\n";

    static final String NEBULA =
          "uniform float2 uResolution;\n"
        + "uniform float uTime;\n"
        + "const float PI = 3.14159265359;\n"
        + "const float TAU = 6.28318530718;\n"
        + "float hash(float2 p) {\n"
        + "    float3 q = fract(float3(p.xyx) * .1031);\n"
        + "    q += dot(q, q.yzx + 33.33);\n"
        + "    return fract((q.x + q.y) * q.z);\n"
        + "}\n"
        + "float noise(float2 p) {\n"
        + "    float2 cell = floor(p), f = fract(p);\n"
        + "    float2 u = f*f*f*(f*(f*6.0-15.0)+10.0);\n"
        + "    return mix(mix(hash(cell),hash(cell+float2(1.0,0.0)),u.x),\n"
        + "               mix(hash(cell+float2(0.0,1.0)),hash(cell+1.0),u.x),u.y);\n"
        + "}\n"
        + "float fbm(float2 p) {\n"
        + "    float value=0.0, weight=.5;\n"
        + "    for(int octave=0;octave<5;octave++) {\n"
        + "        value+=weight*noise(p);\n"
        + "        p=float2x2(.8,.6,-.6,.8)*p*2.04+float2(12.7,6.3);\n"
        + "        weight*=.49;\n"
        + "    }\n"
        + "    return value;\n"
        + "}\n"
        + "float2 rotatePoint(float2 p,float a) {\n"
        + "    return float2(cos(a)*p.x-sin(a)*p.y,sin(a)*p.x+cos(a)*p.y);\n"
        + "}\n"
        + "float3 starLayer(float2 p,float scale,float threshold) {\n"
        + "    float2 cell=floor(p*scale), local=fract(p*scale);\n"
        + "    float2 offset=float2(hash(cell+17.0),hash(cell+61.0))*.6+.2;\n"
        + "    float2 d=local-offset;\n"
        + "    float seed=hash(cell);\n"
        + "    float core=exp(-dot(d,d)*500.0);\n"
        + "    float rays=exp(-abs(d.x)*200.0-abs(d.y)*14.0)\n"
        + "              +exp(-abs(d.y)*200.0-abs(d.x)*14.0);\n"
        + "    float bright=step(.998,seed);\n"
        + "    float3 tint=mix(float3(.35,.52,1.0),float3(1.0,.85,.72),hash(cell+4.0));\n"
        + "    return tint*(core*(.35+seed)+rays*bright*.4)*step(threshold,seed);\n"
        + "}\n"
        + "float3 nebula(float2 p,float t) {\n"
        + "    float2 q=rotatePoint(p,-.39);\n"
        + "    float2 drift=float2(t*.008,-t*.003);\n"
        + "    float2 base=q*1.6+drift;\n"
        + "    float2 flow=float2(fbm(base+8.3),fbm(base+float2(4.1,-2.7)));\n"
        + "    float broad=fbm(base+flow*2.7);\n"
        + "    float detail=fbm(base*3.8+flow*4.1+float2(t*.005,0.0));\n"
        + "    float lace=fbm(base*10.0+flow*5.0+detail*2.0);\n"
        + "    float spine=q.y+.12*sin(q.x*2.2)+.16*(flow.x-.5);\n"
        + "    float envelope=exp(-spine*spine*3.6);\n"
        + "    float density=smoothstep(.25,.76,broad)*envelope;\n"
        + "    float carved=smoothstep(.30,.61,detail);\n"
        + "    float filaments=pow(max(0.0,1.0-abs(detail-.54)*5.0),3.0)*lace;\n"
        + "    float embers=exp(-dot((q-float2(.48,.08))*float2(1.1,2.0),(q-float2(.48,.08))*float2(1.1,2.0)));\n"
        + "    float3 pigment=mix(float3(.025,.055,.38),float3(.37,.045,.57),smoothstep(.3,.65,broad));\n"
        + "    pigment=mix(pigment,float3(.95,.13,.34),embers*smoothstep(.38,.65,detail));\n"
        + "    pigment=mix(pigment,float3(1.0,.48,.16),embers*pow(smoothstep(.47,.73,detail),1.5));\n"
        + "    float3 color=float3(.0015,.002,.008);\n"
        + "    color+=float3(.015,.025,.09)*envelope*.3;\n"
        + "    color+=pigment*density*(.23+carved*1.7+filaments*.9);\n"
        + "    color*=.48+.52*smoothstep(.20,.52,detail);\n"
        + "    color+=mix(float3(.20,.35,1.0),float3(1.0,.48,.38),embers)*filaments*density*.18;\n"
        + "    color+=starLayer(p,160.0,.992)+starLayer(p+7.0,51.0,.986)*1.4;\n"
        + "    return color;\n"
        + "}\n"
        + "float3 finishColor(float3 color,float2 p) {\n"
        + "    // A restrained filmic shoulder preserves saturated highlights.\n"
        + "    color=1.0-exp(-max(color,float3(0.0))*1.65);\n"
        + "    color*=1.0-.12*smoothstep(.55,2.2,length(p*float2(.65,1.0)));\n"
        + "    return pow(max(color,float3(0.0)),float3(.91));\n"
        + "}\n"
        + "half4 main(float2 fragCoord) {\n"
        + "    float2 p=(fragCoord-.5*uResolution)/uResolution.y*2.0;\n"
        + "    p.y=-p.y;\n"
        + "    float3 color=finishColor(nebula(p,uTime),p);\n"
        + "    return half4(half3(color),1.0);\n"
        + "}\n";

    static final String BLOOM =
          "uniform float2 uResolution;\n"
        + "uniform float uTime;\n"
        + "const float PI = 3.14159265359;\n"
        + "const float TAU = 6.28318530718;\n"
        + "float3 bloom(float2 p,float t) {\n"
        + "    float2 q=p-float2(0.0,.06);\n"
        + "    float r=length(q), a=atan(q.y,q.x);\n"
        + "    float3 color=float3(.006,.002,.016);\n"
        + "    color+=float3(.085,.008,.075)*exp(-r*r*2.6);\n"
        + "    for(int layer=0;layer<8;layer++) {\n"
        + "        float k=float(layer);\n"
        + "        float size=.98*pow(.80,k)*(1.0+.035*sin(t*.07+k*.8));\n"
        + "        float petals=10.0+mod(k,3.0);\n"
        + "        float rotation=t*(.014+k*.0015)*(mod(k,2.0)*2.0-1.0)+k*.39;\n"
        + "        float sector=TAU/petals;\n"
        + "        float angle=mod(a-rotation+r*(.9+.12*sin(t*.04))+sector*.5,sector)-sector*.5;\n"
        + "        float2 local=float2(cos(angle),sin(angle))*r;\n"
        + "        float u=(local.x-.025)/size;\n"
        + "        float valid=step(0.0,u)*(1.0-step(1.0,u));\n"
        + "        float taper=pow(max(0.0,sin(clamp(u,0.0,1.0)*PI)),.78);\n"
        + "        float halfWidth=size*.225*taper+.0006;\n"
        + "        float curl=sin(clamp(u,0.0,1.0)*PI)*size*.045*sin(k*.7+t*.035);\n"
        + "        float crossSection=(local.y-curl)/halfWidth;\n"
        + "        float dist=abs(crossSection);\n"
        + "        float aa=clamp(3.0/uResolution.y/halfWidth,.012,.3);\n"
        + "        float fill=(1.0-smoothstep(1.0-aa,1.0+aa,dist))*valid;\n"
        + "        float rim=exp(-pow((dist-.92)*22.0,2.0))*valid;\n"
        + "        float vein=exp(-pow(crossSection*24.0,2.0))*valid*taper;\n"
        + "        float light=.18+.40*pow(clamp(.5+.5*crossSection,0.0,1.0),2.0)+.32*u;\n"
        + "        float3 pigment=mix(float3(.32,.018,.7),float3(1.0,.23,.46),k/7.0);\n"
        + "        pigment=mix(pigment,float3(1.0,.66,.37),pow(k/7.0,3.0));\n"
        + "        color*=1.0-fill*.24;\n"
        + "        color+=pigment*(fill*light*.32+rim*.72+vein*.13);\n"
        + "        color+=mix(pigment,float3(1.0,.78,.66),.45)*rim*pow(max(0.0,u),3.0)*.23;\n"
        + "    }\n"
        + "    color+=float3(1.0,.57,.31)*exp(-r*r*950.0)*1.3;\n"
        + "    color+=float3(1.0,.25,.28)*exp(-r*r*75.0)*.13;\n"
        + "    return color;\n"
        + "}\n"
        + "float3 finishColor(float3 color,float2 p) {\n"
        + "    // A restrained filmic shoulder preserves saturated highlights.\n"
        + "    color=1.0-exp(-max(color,float3(0.0))*1.65);\n"
        + "    color*=1.0-.12*smoothstep(.55,2.2,length(p*float2(.65,1.0)));\n"
        + "    return pow(max(color,float3(0.0)),float3(.91));\n"
        + "}\n"
        + "half4 main(float2 fragCoord) {\n"
        + "    float2 p=(fragCoord-.5*uResolution)/uResolution.y*2.0;\n"
        + "    p.y=-p.y;\n"
        + "    float3 color=finishColor(bloom(p,uTime),p);\n"
        + "    return half4(half3(color),1.0);\n"
        + "}\n";

    private DesignSceneSources() {}
}
