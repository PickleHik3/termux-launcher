package com.termux.app.chrome.scene;

/**
 * The AGSL of Coastal Sunset, the developer's sample shader verbatim: a centre-crop cover of the
 * 746 x 1536 artwork ({@link SceneArtwork}), sea ripples, a glint on the sun's reflection and two
 * drawn birds over the erased static ones. Uniforms: {@code artwork} (input shader), {@code resolution}
 * and {@code imageSize} (px), {@code time} (seconds), {@code motion} (0 still .. 1 full).
 */
final class CoastalSunsetSource {

    static final String AGSL =
        "// Pixel coordinates in this program correspond to the supplied 746x1536 artwork.\n"
        + "// A centered cover transform maps the device screen to artwork pixels.\n"
        + "uniform shader artwork;\n"
        + "uniform float2 resolution;\n"
        + "uniform float2 imageSize;\n"
        + "uniform float time;\n"
        + "uniform float motion; // 0 = still, 1 = normal\n"
        + "\n"
        + "float sdSegment(float2 p, float2 a, float2 b) {\n"
        + "    float2 q = p - a;\n"
        + "    float2 d = b - a;\n"
        + "    return length(q - d * clamp(dot(q, d) / max(dot(d, d), 0.0001), 0.0, 1.0));\n"
        + "}\n"
        + "\n"
        + "float removeBirdPatch(float2 p, float2 center, float2 radius) {\n"
        + "    float2 v = abs(p - center) - radius;\n"
        + "    return 1.0 - smoothstep(0.0, 7.0, max(v.x, v.y));\n"
        + "}\n"
        + "\n"
        + "float birdShape(float2 p, float2 center, float size, float phase) {\n"
        + "    float2 q = (p - center) / size;\n"
        + "    float flap = sin(phase);\n"
        + "    // The two wings form an articulated shallow V. Wing tips bend when flapping.\n"
        + "    float2 shoulder = float2(0.0, 0.0);\n"
        + "    float2 leftMid = float2(-0.40, -0.13 - 0.23 * flap);\n"
        + "    float2 leftTip = float2(-1.0, -0.07 - 0.64 * flap);\n"
        + "    float2 rightMid = float2(0.40, -0.13 - 0.23 * flap);\n"
        + "    float2 rightTip = float2(1.0, -0.07 - 0.64 * flap);\n"
        + "    float d = min(sdSegment(q, shoulder, leftMid), sdSegment(q, leftMid, leftTip));\n"
        + "    d = min(d, sdSegment(q, shoulder, rightMid));\n"
        + "    d = min(d, sdSegment(q, rightMid, rightTip));\n"
        + "    float body = length(float2(q.x * 2.2, (q.y - 0.035) * 5.0)) - 0.15;\n"
        + "    return 1.0 - smoothstep(0.035, 0.095, min(d, body));\n"
        + "}\n"
        + "\n"
        + "half4 main(float2 canvasPos) {\n"
        + "    float scaleFactor = max(resolution.x / imageSize.x, resolution.y / imageSize.y);\n"
        + "    float2 p = (canvasPos - 0.5 * resolution) / scaleFactor + 0.5 * imageSize;\n"
        + "    float2 source = p;\n"
        + "\n"
        + "    // Water starts at y ~946 in the reference; keep cliffs, tree and pavilion sharp.\n"
        + "    // The approximate coastline boundary tracks left as the rocky bluff descends.\n"
        + "    float shorelineX = 395.0 - 0.70 * max(p.y - 945.0, 0.0);\n"
        + "    float oceanMask = smoothstep(941.0, 965.0, p.y) *\n"
        + "                      (1.0 - smoothstep(shorelineX - 23.0, shorelineX + 8.0, p.x));\n"
        + "    float farToNear = clamp((p.y - 945.0) / 591.0, 0.0, 1.0);\n"
        + "    float wave1 = sin(p.y * (0.13 + 0.08 * farToNear) - time * 1.0 + sin(p.x * 0.018));\n"
        + "    float wave2 = sin(p.y * 0.29 + p.x * 0.045 + time * 1.35);\n"
        + "    float wave3 = sin(p.y * 0.065 - p.x * 0.028 - time * 0.70);\n"
        + "    source.x += motion * oceanMask * (1.5 + 3.6 * farToNear) *\n"
        + "                (0.58 * wave1 + 0.28 * wave2 + 0.14 * wave3);\n"
        + "    source.y += motion * oceanMask * 0.8 * sin(p.x * 0.042 + time * 0.8);\n"
        + "\n"
        + "    half4 color = artwork.eval(source);\n"
        + "\n"
        + "    // Replace two original stationary bird silhouettes with nearby sky samples,\n"
        + "    // then draw two independent animated silhouettes on top.\n"
        + "    float patch1 = removeBirdPatch(p, float2(141.0, 544.0), float2(39.0, 19.0));\n"
        + "    float patch2 = removeBirdPatch(p, float2(207.0, 599.0), float2(36.0, 16.0));\n"
        + "    float erased = max(patch1, patch2);\n"
        + "    // The sky changes with height, not across: patch from the same height, to the right.\n"
        + "    half4 cleanSky = artwork.eval(float2(p.x + 100.0, p.y));\n"
        + "    color = mix(color, cleanSky, half(erased));\n"
        + "\n"
        + "    // Shimmer across the sun's reflection: localized, thin, moving highlights.\n"
        + "    float glintRegion = oceanMask * (1.0 - smoothstep(1170.0, 1410.0, p.y));\n"
        + "    float stripe = pow(max(0.0, sin(p.y * 0.32 - time * 1.8 + sin(p.x * 0.05))), 15.0);\n"
        + "    float glintCenter = 312.0 + 22.0 * sin(p.y * 0.014 + time * 0.12);\n"
        + "    float glintWidth = 90.0 + 75.0 * farToNear;\n"
        + "    float glint = glintRegion * stripe * exp(-pow((p.x - glintCenter) / glintWidth, 2.0));\n"
        + "    color.rgb += half3(0.072, 0.055, 0.024) * half(glint * motion);\n"
        + "\n"
        + "    // Atmospheric light pulsing is deliberately subtle and excludes dark foreground.\n"
        + "    float glow = (1.0 - smoothstep(850.0, 1030.0, p.y)) *\n"
        + "                 exp(-pow((p.x - 310.0) / 280.0, 2.0));\n"
        + "    color.rgb += half3(0.009, 0.006, 0.001) * half(glow * motion * sin(time * 0.37));\n"
        + "\n"
        + "    float flight1 = time * 0.30;\n"
        + "    float flight2 = time * 0.23;\n"
        + "    float2 bird1 = float2(141.0 + motion * 17.0 * sin(flight1),\n"
        + "                          544.0 + motion * 5.0 * sin(time * 0.47));\n"
        + "    float2 bird2 = float2(207.0 + motion * 24.0 * sin(flight2 + 1.7),\n"
        + "                          599.0 + motion * 6.0 * sin(time * 0.41 + 0.7));\n"
        + "    float b1 = birdShape(p, bird1, 26.0, time * 2.2 + 0.7);\n"
        + "    float b2 = birdShape(p, bird2, 20.0, time * 2.55 + 2.1);\n"
        + "    color.rgb = mix(color.rgb, half3(0.025, 0.19, 0.23), half(max(b1, b2)));\n"
        + "    return half4(color.rgb, 1.0);\n"
        + "}\n";

    private CoastalSunsetSource() {}
}
