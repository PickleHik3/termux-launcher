#!/usr/bin/env python3
"""Regenerate the settings rows' Material Symbols vector drawables.

Reads every R.drawable.ic_ms_<name> named in SettingsRowIcons.java, downloads the matching
Material Symbols Rounded SVG (24px, weight 400, no fill) from the official
google/material-design-icons repository, and writes res/drawable/ic_ms_<name>.xml. The SVGs are
fetched into a temporary directory and never kept in the repository.

Run from the repository root:

    scripts/material-symbols-vectors.py            # fetch what is missing
    scripts/material-symbols-vectors.py --force    # rewrite every drawable
"""

import argparse
import os
import re
import sys
import tempfile
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET

SOURCE = "app/src/main/java/com/termux/app/fragments/settings/SettingsRowIcons.java"
OUT_DIR = "app/src/main/res/drawable"
URL = ("https://raw.githubusercontent.com/google/material-design-icons/master/"
       "symbols/web/{name}/materialsymbols{style}/{name}_24px.svg")
SVG_NS = "{http://www.w3.org/2000/svg}"
FILL = "?attr/colorOnSurfaceVariant"


def names_in(source):
    with open(source, encoding="utf-8") as handle:
        return sorted(set(re.findall(r"R\.drawable\.ic_ms_(\w+)", handle.read())))


def fetch(name, style, workdir):
    target = os.path.join(workdir, name + ".svg")
    with urllib.request.urlopen(URL.format(name=name, style=style), timeout=30) as response:
        data = response.read()
    with open(target, "wb") as handle:
        handle.write(data)
    return target


def vector(svg_path):
    root = ET.parse(svg_path).getroot()
    # Most symbols draw in a 0 -960 960 960 box; a few older ones still use a 24-unit one with no
    # viewBox, only width and height.
    box = root.get("viewBox") or "0 0 %s %s" % (root.get("width", "24"), root.get("height", "24"))
    min_x, min_y, width, height = (float(v) for v in box.replace(",", " ").split())
    paths = [p.get("d") for p in root.iter(SVG_NS + "path") if p.get("d")]
    others = {key for p in root.iter(SVG_NS + "path") for key in p.keys() if key != "d"}
    if others or any(True for e in root.iter() if e.tag not in (SVG_NS + "svg", SVG_NS + "path")):
        raise ValueError("unexpected markup in %s: %s" % (svg_path, sorted(others)))
    if not paths:
        raise ValueError("no path in " + svg_path)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Material Symbols Rounded; generated by scripts/material-symbols-vectors.py -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="%g"' % width,
        '    android:viewportHeight="%g">' % height,
    ]
    # Shift the box back into the viewport.
    lines.append('    <group android:translateX="%g" android:translateY="%g">' % (0.0 - min_x + 0.0, 0.0 - min_y + 0.0))
    for d in paths:
        lines.append('        <path android:fillColor="%s" android:pathData="%s" />' % (FILL, d))
    lines.append("    </group>")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", default=SOURCE)
    parser.add_argument("--out", default=OUT_DIR)
    parser.add_argument("--style", default="rounded", choices=["rounded", "outlined", "sharp"])
    parser.add_argument("--force", action="store_true", help="rewrite drawables that exist")
    args = parser.parse_args()

    failed = []
    written = 0
    with tempfile.TemporaryDirectory(prefix="material-symbols-") as workdir:
        for name in names_in(args.source):
            out = os.path.join(args.out, "ic_ms_%s.xml" % name)
            if os.path.exists(out) and not args.force:
                continue
            try:
                content = vector(fetch(name, args.style, workdir))
            except (urllib.error.URLError, ValueError, ET.ParseError) as error:
                failed.append("%s: %s" % (name, error))
                continue
            with open(out, "w", encoding="utf-8") as handle:
                handle.write(content)
            written += 1
    print("wrote %d drawable(s)" % written)
    for line in failed:
        print("failed " + line, file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
